"""Writes tracker/SOURCES.md, Isaac's private reference.

The file is listed in .gitignore and is never published. It holds the
method with the current numbers filled in, the defaults for each country,
the open items, and every source behind the figures. A part written by hand
between the two KEPT markers is carried over each time the file is written.

build.py runs this after the data files are written. It can also be run on
its own:

    tracker/pipeline/.venv/bin/python tracker/pipeline/sources_doc.py
"""

import json
import os

import yaml

from helpers import DATA, HERE, MANUAL

SHOWN = ("united-states", "japan", "canada")   # the countries on the page
OUTPUT = os.path.join(HERE, "..", "SOURCES.md")
KEPT_START = "<!-- Written by hand: kept when this file is regenerated -->"
KEPT_END = "<!-- End of the part written by hand -->"


def main():
    with open(os.path.join(HERE, "sources.yml")) as f:
        sources = yaml.safe_load(f)["sources"]
    with open(os.path.join(HERE, "series.yml")) as f:
        series_list = yaml.safe_load(f)["series"]
    presets = read_json("presets.json")
    estimates = read_json("estimates.json")
    meta = read_json("meta.json")
    countries = {key: read_json(key + ".json") for key in SHOWN}

    lines = [
        "# Sovereign debt simulator: sources and method",
        "",
        "Private reference. Generated by `tracker/pipeline/sources_doc.py` on "
        + meta["lastSuccessfulRun"] + ". Not published and not committed.",
        "",
    ]
    lines += kept_part()
    lines += method(presets, estimates)
    lines += defaults(countries)
    lines += illustrative(presets)
    lines += open_items(sources, countries)
    lines += source_entries(sources, series_list, meta, countries)
    lines += manual_files()

    with open(OUTPUT, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("Wrote SOURCES.md (private, not committed).")


def kept_part():
    """The part of the existing file written by hand, markers included, or
    nothing if there is none."""
    if not os.path.exists(OUTPUT):
        return []
    with open(OUTPUT) as f:
        text = f.read()
    if KEPT_START not in text or KEPT_END not in text:
        return []
    inside = text.split(KEPT_START, 1)[1].split(KEPT_END, 1)[0].strip("\n")
    return [KEPT_START, inside, KEPT_END, ""]


def read_json(name):
    with open(os.path.join(DATA, name)) as f:
        return json.load(f)


def percent(value, places=1):
    return f"{value * 100:.{places}f}%"


# ---------------------------------------------------------------- method

def method(presets, estimates):
    controls = presets["controls"]
    share = estimates["moneyShare"]
    return [
        "## The model",
        "",
        "`runModel` in `tracker/js/model.js` projects one country 30 years ahead in annual steps. Quantities "
        "are shares of GDP, rates are annual. The numbers match the comments in the code.",
        "",
        "    1. implied  = (1 + M2 growth[t-1]) / ((1 + g) x (1 + trend)) - 1",
        "       inflation = implied + persistence x (inflation[t-1] - implied)",
        "       nominal growth n = (1 + g) x (1 + inflation) - 1",
        "    2. average rate = (1 - 1/maturity) x average rate[t-1] + (1/maturity) x yield[t-1]",
        "    3. debt = debt[t-1] x (1 + average rate) / (1 + n) - primary balance",
        "    4. stress: interest > share x revenue, or the debt-stabilizing balance > the country's best",
        "       five-year average primary balance",
        "    5-6. M = debt that price-sensitive holders must absorb beyond their starting holdings,",
        "       with the central bank keeping its share of the debt",
        "    7. market yield = starting yield + (inflation - starting inflation)",
        "                      + yield response x M + selloff response x selloff overhang   (not below 0)",
        "    8. cap: above it the central bank buys until the yield is at the cap, up to its limit",
        "    10. M2 growth = base M2 growth + new-money share x rise in central bank holdings / M2[t-1]",
        "",
        "- **Persistence** " + f"{controls['persistence']['default']:.2f}" + ", hidden. **Trend**: the "
        "country's average rise in M2 against GDP (falling velocity).",
        "- **Cap.** Default fixed at " + percent(controls["capLevel"]["default"], 0) + ". Stress level: each "
        "year `share x revenue / debt`, the yield at which interest would hit the stress share once the whole "
        "debt pays it. Off: no buying beyond keeping its share. **Limit** "
        + percent(controls["centralBankLimit"]["default"], 0) + " of the debt; beyond it the cap fails. "
        "**Fiscal dominance**: any year it buys to hold the cap, or the cap has failed.",
        "- **New-money share** " + f"{share['value']:.2f}" + ": " + share["note"] + " ("
        + ", ".join(f"{key} {item['value']:.2f}" for key, item in share["byCountry"].items()) + "). Money "
        "is destroyed only when holdings fall in money terms, not merely against GDP.",
        "- **Selloff.** Foreign holders sell a share evenly over the chosen years. Unabsorbed debt adds "
        + f"{controls['selloffResponse']['default'] * 100:.0f}" + " bp per point of GDP; half of it is "
        "absorbed each year, so the premium fades.",
        "- **Headlines.** Debasement = `1 - 1/price level` after 30 years, annualized as "
        "`1 - (1 - loss)^(1/30)`. Money supply expansion = compounded M2 growth, annualized.",
        "- **Tests**: `node --test tracker/tests/model.test.js` (hand calculations on an invented country).",
        "",
    ]


# ---------------------------------------------------------------- 2. defaults

def defaults(countries):
    rows = (
        ("Starting year", lambda s: str(s["year"])),
        ("Debt", lambda s: percent(s["debt"]["value"]) + " of GDP"),
        ("Central bank holdings", lambda s: percent(s["centralBank"]["value"]) + " of GDP"),
        ("10-year yield", lambda s: percent(s["yield"]["value"], 2)),
        ("Average interest rate", lambda s: percent(s["averageRate"]["value"], 2)),
        ("Average maturity", lambda s: f"{s['maturity']['value']:.1f} years"),
        ("Inflation", lambda s: percent(s["inflation"]["value"])),
        ("Revenue", lambda s: percent(s["revenue"]["value"]) + " of GDP"),
        ("Money supply (M2)", lambda s: percent(s["money"]["value"], 0) + " of GDP"),
        ("Default: primary balance", lambda s: percent(s["baselinePrimaryBalance"]["value"])),
        ("Default: real growth (IMF projection)", lambda s: percent(s["growth"]["value"])),
        ("Average real growth since 1972, for comparison", lambda s: percent(s["baselineGrowth"]["value"])),
        ("Base money growth", lambda s: percent(s["moneyGrowth"]["value"])),
        ("Money drift", lambda s: percent(s["moneyTrend"]["value"])),
        ("Implied inflation", lambda s: percent(
            (1 + s["moneyGrowth"]["value"])
            / ((1 + s["growth"]["value"]) * (1 + s["moneyTrend"]["value"])) - 1)),
        ("Average inflation since 1972, for comparison", lambda s: percent(s["baselineInflation"]["value"])),
        ("Stress threshold (balance test)", lambda s: "not used" if s["stressThreshold"]["value"] is None
            else percent(s["stressThreshold"]["value"])),
    )
    names = [countries[key]["name"] for key in SHOWN]
    lines = [
        "## Defaults by country",
        "",
        "| | " + " | ".join(names) + " |",
        "|---|" + "---|" * len(names),
    ]
    for label, value in rows:
        lines.append("| " + label + " | " + " | ".join(value(countries[key]["start"]) for key in SHOWN) + " |")
    lines += ["", "Where each default comes from:", ""]
    for key in SHOWN:
        start = countries[key]["start"]
        lines.append("**" + countries[key]["name"] + "** (" + countries[key]["yearBasis"] + " "
                     + countries[key]["governmentCovered"] + ")")
        lines.append("")
        for name, label in (("baselinePrimaryBalance", "Primary balance"), ("growth", "Real growth"),
                            ("moneyGrowth", "Base money growth"), ("moneyTrend", "Money drift"),
                            ("stressThreshold", "Stress threshold")):
            lines.append("- " + label + ": " + start[name]["note"] + ". Sources: "
                         + ", ".join(start[name]["source"]) + ".")
        for note in countries[key].get("notes") or []:
            lines.append("- Note on the page: " + note)
        lines.append("")
    return lines


# ---------------------------------------------------------------- 3. illustrative

def illustrative(presets):
    labels = {
        "stressInterestShare": "Interest burden that counts as fiscal stress",
        "capLevel": "Yield cap level",
        "centralBankLimit": "Most the central bank will hold",
        "selloffShare": "Foreign selloff: share sold",
        "selloffResponse": "Foreign selloff: yield rise from selling",
        "selloffYears": "Foreign selloff: years",
        "persistence": "Inflation persistence",
        "runoff": "Central bank runoff (not shown on the page)",
        "yieldResponse": "Yield response",
    }
    lines = [
        "## Illustrative assumptions",
        "",
        "Not estimated from data. The page labels each one illustrative.",
        "",
        "| Setting | Default | Note in the presets file |",
        "|---|---|---|",
    ]
    for key, preset in presets["controls"].items():
        if preset.get("illustrative"):
            lines.append(f"| {labels.get(key, key)} | {preset['default']} | {preset['basis']} |")
    for group, preset in presets["priceSensitive"]["defaults"].items():
        lines.append(f"| Price-sensitive share: {group} (not shown on the page) | {preset['default']} | "
                     f"{preset['basis']} |")
    lines += [
        "",
        "Values are fractions: 0.3 is 30%, and a yield response of 0.03 is 3 basis points for each point "
        "of GDP. Where the data gives a price-sensitive share for domestic holders, it replaces the "
        "default above.",
        "",
    ]
    return lines


# ---------------------------------------------------------------- open items

def open_items(sources, countries):
    used = used_sources(countries)
    unconfirmed = [key for key in sources if key in used and "to confirm" in json.dumps(sources[key]).lower()]
    return [
        "## Open items and known limits",
        "",
        f"- {len(unconfirmed)} of the {len(used)} sources still have a field marked \"to confirm\" in "
        "`sources.yml`, mostly terms of reuse (marked * below).",
        "- Japan and Canada's holder sectors follow the United States rule by analogy.",
        "- Japan: revenue leaves out the surplus carried over; debt history starts in 2022; no balance test.",
        "- Canada: revenue counts federal transfers to provinces twice (3.3 points of GDP; no effect on "
        "the default results). The primary balance is the IMF's all-government figure.",
        "- The selloff response has no published basis; it is illustrative.",
        "",
    ]


def used_sources(countries):
    """The keys of every source that a figure in the shown countries'
    data files names."""
    used = set()
    for country in countries.values():
        items = list(country["start"].values()) + list(country["start"].get("holdings", {}).values()) \
            + list(country["history"].values()) + list(country["parameters"].get("priceSensitive", {}).values())
        for item in items:
            if isinstance(item, dict):
                used.update(item.get("source") or [])
    return used


# ---------------------------------------------------------------- sources

def source_entries(sources, series_list, meta, countries):
    """One line per source. The full entry for each is in sources.yml."""
    used = used_sources(countries)
    lines = [
        "## Sources",
        "",
        "The full entry for each is under the same key in `tracker/pipeline/sources.yml`.",
        "",
        "| Key | Source | Used for | Series or file | Retrieved |",
        "|---|---|---|---|---|",
    ]
    for key, entry in sources.items():
        if key not in used:
            continue
        fetched = [series for series in series_list if series["source"] == key and series["country"] in SHOWN]
        if fetched:
            names = [str(series.get("id") or series.get("indicator") or series.get("series")
                         or series.get("endpoint")) for series in fetched]
            what = ", ".join(dict.fromkeys(names))   # each name once, in order
        else:
            what = "manual file"
        star = "*" if "to confirm" in json.dumps(entry).lower() else ""
        lines.append(f"| `{key}`{star} | {entry['publisher']}, {entry['name']} | "
                     f"{' '.join(str(entry['used_for']).split()).replace('the United Kingdom, ', '')} | {what} | "
                     f"{meta['sources'].get(key, {}).get('retrievedOn', '')} |")
    lines.append("")
    return lines


# ---------------------------------------------------------------- manual files

def manual_files():
    lines = [
        "## Manual files",
        "",
        "In `tracker/pipeline/manual/`, one parser each; `notes.txt` in each folder says where from and when.",
        "",
    ]
    for key in SHOWN:
        path = os.path.join(MANUAL, key)
        if os.path.isdir(path):
            names = sorted(name for name in os.listdir(path) if name != "notes.txt")
            lines.append(f"- {key}: " + ", ".join(f"`{name}`" for name in names))
    lines.append("")
    return lines


if __name__ == "__main__":
    main()
