"""Writes tracker/SOURCES.md, Isaac's private reference.

The file is listed in .gitignore and is never published. It has two parts:
a summary of the method, with the current numbers filled in, for Isaac to
write the methodology page from; and every source in sources.yml, with the
series, files and rules behind each figure.

build.py runs this after the data files are written. It can also be run on
its own:

    tracker/pipeline/.venv/bin/python tracker/pipeline/sources_doc.py
"""

import json
import os

import yaml

from helpers import DATA, HERE, MANUAL

SHOWN = ("united-states", "japan", "canada")   # the countries on the page
OUTPUT = os.path.join(HERE, "..", "SOURCES.md")

FIELDS = (
    ("publisher", "Publisher"), ("address", "Address"), ("measures", "What it measures"),
    ("used_for", "Used for"), ("definition_notes", "Definitions"),
    ("units_and_frequency", "Units and frequency"), ("category_mapping", "Category mapping"),
    ("retrieval", "How it is retrieved"), ("reuse_terms", "Terms of reuse"), ("known_limits", "Known limits"),
)


def main():
    with open(os.path.join(HERE, "sources.yml")) as f:
        sources = yaml.safe_load(f)["sources"]
    with open(os.path.join(HERE, "series.yml")) as f:
        series_list = yaml.safe_load(f)["series"]
    presets = read_json("presets.json")
    estimates = read_json("estimates.json")
    meta = read_json("meta.json")
    countries = {key: read_json(key + ".json") for key in SHOWN}

    lines = [
        "# Sovereign debt simulator: sources and method",
        "",
        "Private reference. Generated by `tracker/pipeline/sources_doc.py` on "
        + meta["lastSuccessfulRun"] + ". Not published and not committed.",
        "",
        "Contents: 1. Method summary. 2. Defaults by country. 3. Assumptions that are illustrative. "
        "4. Where the build differs from the specification. 5. Open items. 6. Sources. 7. Manual files.",
        "",
    ]
    lines += method(presets, estimates)
    lines += defaults(countries, presets, estimates)
    lines += illustrative(presets)
    lines += differences()
    lines += open_items(sources, countries)
    lines += source_entries(sources, series_list, meta)
    lines += manual_files()

    with open(OUTPUT, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("Wrote SOURCES.md (private, not committed).")


def read_json(name):
    with open(os.path.join(DATA, name)) as f:
        return json.load(f)


def percent(value, places=1):
    return f"{value * 100:.{places}f}%"


# ---------------------------------------------------------------- 1. method

def method(presets, estimates):
    controls = presets["controls"]
    share = estimates["moneyShare"]
    return [
        "## 1. Method summary",
        "",
        "One function, `runModel` in `tracker/js/model.js`, projects one country 30 years ahead in yearly "
        "steps. Every quantity is a share of GDP; every rate is per year. The steps below are in the order "
        "the model runs them each year. `t` is the year and `t-1` the year before.",
        "",
        "**1. Inflation.** Inflation follows the money supply (M2).",
        "",
        "    implied inflation = (1 + money growth[t-1]) / ((1 + real growth) x (1 + money drift)) - 1",
        "    inflation[t]      = implied inflation + persistence x (inflation[t-1] - implied inflation)",
        "",
        "Money drift is how much faster than GDP the money supply has grown each year without raising "
        "prices: the average yearly rise in M2 as a share of GDP. Persistence is the part of last year's "
        "gap that remains (default " + f"{controls['persistence']['default']:.2f}" + ").",
        "",
        "**2. Nominal growth.** `(1 + real growth) x (1 + inflation) - 1`.",
        "",
        "**3. Average interest rate.** One part in `maturity` of the debt reprices each year at last "
        "year's yield:",
        "",
        "    average rate[t] = (1 - 1/maturity) x average rate[t-1] + (1/maturity) x yield[t-1]",
        "",
        "**4. Debt.**",
        "",
        "    debt[t] = debt[t-1] x (1 + average rate) / (1 + nominal growth) - primary balance",
        "",
        "The primary balance is one fixed number for all 30 years.",
        "",
        "**5. Fiscal stress.** A year is in fiscal stress when either test is met:",
        "",
        "- Balance test: the primary balance needed to hold debt steady, "
        "`debt[t-1] x (average rate - nominal growth) / (1 + nominal growth)`, is more than the largest "
        "five-year average primary balance in the country's history. Not used for Japan (section 2).",
        "- Interest test: interest, `average rate x debt[t-1] / (1 + nominal growth)`, is more than a set "
        "share of government revenue (default " + percent(controls["stressInterestShare"]["default"], 0) + ").",
        "",
        "**6. Yield cap.** In automatic mode the central bank sets a cap in the first stress year, at the "
        "yield of the year before, and keeps it. The other modes are a fixed level and off.",
        "",
        "**7. Holders.** Each holder group has a captive part, which keeps its share of the debt, and a "
        "price-sensitive part. The central bank, when not intervening, keeps the share of the debt it held "
        "the year before. What is left over is what price-sensitive holders must absorb beyond their "
        "starting holdings (`M`).",
        "",
        "**8. Market yield.**",
        "",
        "    market yield = starting yield + (inflation - starting inflation)",
        "                   + yield response x M + selloff response x selloff overhang",
        "",
        "It is not allowed below zero. Yield response default: "
        + f"{controls['yieldResponse']['default'] * 100:.0f}" + " basis points for each point of GDP.",
        "",
        "**9. Intervention.** If the market yield is above the cap, the central bank buys enough debt to "
        "bring it down to the cap. It stops at a set share of the debt (default "
        + percent(controls["centralBankLimit"]["default"], 0) + "). If that is not enough, the cap fails and "
        "the yield is the market yield at that level of holdings. Fiscal dominance: any year in which the "
        "central bank buys to hold the cap, or the cap has failed.",
        "",
        "**10. Money supply.**",
        "",
        "    money growth[t] = base money growth",
        "                      + new-money share x (rise in central bank holdings / money supply[t-1])",
        "",
        "Base money growth is the country's average M2 growth (section 2). It is fixed, not a control. The "
        "new-money share is " + f"{share['value']:.2f}" + ": " + share["note"] + ". By country: "
        + ", ".join(f"{key} {item['value']:.2f} ({item['years']} years)"
                    for key, item in share["byCountry"].items()) + ".",
        "",
        "**11. Foreign selloff (scenario).** Every foreign group sells the chosen share of its holdings, "
        "evenly over the chosen years. Price-sensitive holders must absorb what is sold. Debt sold that the "
        "central bank has not bought (the overhang) adds the selloff response to the yield (default "
        + f"{controls['selloffResponse']['default'] * 100:.0f}" + " basis points for each point of GDP). "
        "For the United States, a Japanese repatriation works the same way on Japan-resident holdings.",
        "",
        "**Headline figures.**",
        "",
        "- Currency debasement: `1 - 1 / price level` after 30 years, where the price level is each year's "
        "inflation compounded. Shown as a steady yearly rate: `1 - (1 - loss) ^ (1/30)`.",
        "- Money supply expansion: each year's money growth compounded over 30 years, as a steady yearly rate.",
        "",
        "**Tests.** `node --test tracker/tests/model.test.js`. They cover each step above against hand "
        "calculations for an invented country.",
        "",
    ]


# ---------------------------------------------------------------- 2. defaults

def defaults(countries, presets, estimates):
    rows = (
        ("Starting year", lambda s: str(s["year"])),
        ("Debt", lambda s: percent(s["debt"]["value"]) + " of GDP"),
        ("Central bank holdings", lambda s: percent(s["centralBank"]["value"]) + " of GDP"),
        ("Yield on new borrowing", lambda s: percent(s["yield"]["value"], 2)),
        ("Average interest rate", lambda s: percent(s["averageRate"]["value"], 2)),
        ("Average maturity", lambda s: f"{s['maturity']['value']:.1f} years"),
        ("Inflation", lambda s: percent(s["inflation"]["value"])),
        ("Revenue", lambda s: percent(s["revenue"]["value"]) + " of GDP"),
        ("Money supply (M2)", lambda s: percent(s["money"]["value"], 0) + " of GDP"),
        ("Default: primary balance", lambda s: percent(s["baselinePrimaryBalance"]["value"])),
        ("Default: real growth", lambda s: percent(s["baselineGrowth"]["value"])),
        ("Base money growth", lambda s: percent(s["moneyGrowth"]["value"])),
        ("Money drift", lambda s: percent(s["moneyTrend"]["value"])),
        ("Implied inflation", lambda s: percent(
            (1 + s["moneyGrowth"]["value"])
            / ((1 + s["baselineGrowth"]["value"]) * (1 + s["moneyTrend"]["value"])) - 1)),
        ("Average inflation since 1972, for comparison", lambda s: percent(s["baselineInflation"]["value"])),
        ("Stress threshold (balance test)", lambda s: "not used" if s["stressThreshold"]["value"] is None
            else percent(s["stressThreshold"]["value"])),
    )
    names = [countries[key]["name"] for key in SHOWN]
    lines = [
        "## 2. Defaults by country",
        "",
        "| | " + " | ".join(names) + " |",
        "|---|" + "---|" * len(names),
    ]
    for label, value in rows:
        lines.append("| " + label + " | " + " | ".join(value(countries[key]["start"]) for key in SHOWN) + " |")
    lines += ["", "The period behind each default:", ""]
    for key in SHOWN:
        start = countries[key]["start"]
        lines.append("**" + countries[key]["name"] + "** (" + countries[key]["yearBasis"] + " "
                     + countries[key]["governmentCovered"] + ")")
        lines.append("")
        for name in ("baselinePrimaryBalance", "baselineGrowth", "moneyGrowth", "moneyTrend", "stressThreshold"):
            lines.append("- " + start[name]["note"] + ". Sources: " + ", ".join(start[name]["source"]) + ".")
        for note in countries[key].get("notes") or []:
            lines.append("- Note on the page: " + note)
        lines.append("")
    return lines


# ---------------------------------------------------------------- 3. illustrative

def illustrative(presets):
    labels = {
        "stressInterestShare": "Interest burden that counts as fiscal stress",
        "centralBankLimit": "Most the central bank will hold",
        "selloffShare": "Foreign selloff: share sold",
        "selloffResponse": "Foreign selloff: yield rise from selling",
        "selloffYears": "Foreign selloff: years",
        "persistence": "Inflation persistence",
        "foreignInflation": "Foreign inflation (moves only the exchange rate, which the page does not show)",
        "runoff": "Central bank runoff (not shown on the page)",
        "yieldResponse": "Yield response",
    }
    lines = [
        "## 3. Assumptions that are illustrative",
        "",
        "These defaults are not estimated from data and not taken from a published source. The page labels "
        "each one as an illustrative assumption.",
        "",
        "| Setting | Default | Note in the presets file |",
        "|---|---|---|",
    ]
    for key, preset in presets["controls"].items():
        if preset.get("illustrative"):
            lines.append(f"| {labels.get(key, key)} | {preset['default']} | {preset['basis']} |")
    for group, preset in presets["priceSensitive"]["defaults"].items():
        lines.append(f"| Price-sensitive share: {group} (not shown on the page) | {preset['default']} | "
                     f"{preset['basis']} |")
    lines += [
        "",
        "Values are fractions: 0.3 is 30%, and a yield response of 0.03 is 3 basis points for each point "
        "of GDP. Where the data gives a price-sensitive share for domestic holders, it replaces the "
        "default above.",
        "",
    ]
    return lines


# ---------------------------------------------------------------- 4. differences

def differences():
    return [
        "## 4. Where the build differs from the specification",
        "",
        "Each change was Isaac's decision on 2026-11-11 or 2026-11-12.",
        "",
        "- Inflation follows the money supply. The specification's rule (baseline inflation plus "
        "pass-through from central bank buying) remains in `model.js` only for a country with no M2 data.",
        "- Fiscal stress has a second test, interest as a share of revenue.",
        "- A central bank that is not intervening keeps its share of the debt, not its share of GDP.",
        "- The central bank stops buying at a set share of the debt. Yields cannot go below zero.",
        "- A foreign selloff covers all foreign holders and has its own yield response.",
        "- Defaults: primary balance is the 2022 to 2026 average; real growth and money growth are "
        "averages from 1972.",
        "- Canada's primary balance comes from the IMF, not Statistics Canada.",
        "- Japan uses the interest test alone for fiscal stress.",
        "- The page shows the United States, Japan and Canada. United Kingdom data is still built but not "
        "shown; it has no M2 series.",
        "- The page shows two charts, debt and yields, always over 30 years. There is no compare view, "
        "holders chart or range choice.",
        "- Step 7 (reactive primary balance, Japan back-test) is dropped. Step 8 (scheduled refresh) is "
        "not built yet.",
        "",
    ]


# ---------------------------------------------------------------- 5. open items

def open_items(sources, countries):
    lines = [
        "## 5. Open items",
        "",
        "Fields in the registry still marked \"to confirm\". None may remain when the branch is merged.",
        "",
    ]
    for key, entry in sources.items():
        fields = [label for name, label in FIELDS if "to confirm" in str(entry.get(name, "")).lower()]
        if fields:
            lines.append(f"- `{key}` ({entry['name']}): " + ", ".join(fields).lower())
    lines += [
        "",
        "Other points to settle:",
        "",
        "- The sector mappings for Japan and Canada follow the United States rule by analogy.",
        "- Japan's revenue leaves out the surplus carried over from the year before.",
        "- Canada's revenue counts federal transfers to provinces twice.",
        "- The yield response default is to be checked against Laubach (2009) and Gamber and Seliski (2019).",
        "- The selloff response default is to be checked against published estimates.",
        "",
    ]
    return lines


# ---------------------------------------------------------------- 6. sources

def source_entries(sources, series_list, meta):
    lines = ["## 6. Sources", ""]
    for key, entry in sources.items():
        lines += [f"### {entry['name']} (`{key}`)", ""]
        retrieved = meta["sources"].get(key, {})
        if retrieved:
            lines.append("- Last retrieved: " + retrieved["retrievedOn"]
                         + (", " + retrieved["edition"] if "edition" in retrieved else ""))
        for name, label in FIELDS:
            if entry.get(name):
                lines.append(f"- {label}: " + " ".join(str(entry[name]).split()))
        lines.append("- Series or tables:")
        for item in entry.get("series_or_tables") or []:
            lines.append("    - " + item)
        lines.append("- Transformations:")
        for item in entry.get("transformations") or []:
            lines.append("    - " + item)
        fetched = [series for series in series_list if series["source"] == key]
        if fetched:
            lines.append("- Fetched automatically:")
            for series in fetched:
                identifier = series.get("id") or series.get("indicator") or series.get("series") \
                    or series.get("endpoint")
                lines.append(f"    - `{series['key']}`: {series['service']} {identifier}. "
                             f"Feeds {series['feeds']}. Yearly rule: {' '.join(str(series['annual_rule']).split())}.")
        lines.append("")
    return lines


# ---------------------------------------------------------------- 7. manual files

def manual_files():
    lines = [
        "## 7. Manual files",
        "",
        "Files downloaded by hand, kept in `tracker/pipeline/manual/`. Each has its own parser in "
        "`tracker/pipeline/parsers/`, which stops if the file's layout is not what it expects.",
        "",
    ]
    for folder in sorted(os.listdir(MANUAL)):
        path = os.path.join(MANUAL, folder)
        if not os.path.isdir(path):
            continue
        lines += [f"### {folder}", ""]
        notes = os.path.join(path, "notes.txt")
        if os.path.exists(notes):
            with open(notes) as f:
                for line in f:
                    if "|" in line and not line.startswith("One line per file"):
                        name, address, table, date = [part.strip() for part in line.split("|", 3)]
                        lines.append(f"- `{name}`: {table.rstrip(chr(46))}. From {address}. Downloaded {date}.")
        else:
            for name in sorted(os.listdir(path)):
                lines.append(f"- `{name}`")
        lines.append("")
    return lines


if __name__ == "__main__":
    main()
